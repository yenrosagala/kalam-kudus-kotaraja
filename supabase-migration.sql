-- ---------------------------------------------------------------------
-- 2. ROW LEVEL SECURITY  (WAJIB - ini yang melindungi database)
--
--    Tanpa baris di bawah, ANON KEY (=kunci publik yang tertanam di
--    halaman web) bisa baca SELEUH database dan menulis bebas.
--    Role postgres selalu lewat RLS, tapi anon harus dibatasi policy.
--
--    anon         = pengunjung tanpa login  -> hanya boleh BACA
--    authenticated= admin yang sudah login -> boleh baca + tulis
-- ---------------------------------------------------------------------
ALTER TABLE public.jadwal_komisi ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mezbah        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.berita        ENABLE ROW LEVEL SECURITY;

--Policies dibuang dulu supaya file ini bisa dijalankan ulang tanpa error
DROP POLICY IF EXISTS "publik baca jadwal"  ON public.jadwal_komisi;
DROP POLICY IF EXISTS "publik baca mezbah"  ON public.mezbah;
DROP POLICY IF EXISTS "publik baca berita"  ON public.berita;
DROP POLICY IF EXISTS "admin tulis jadwal"  ON public.jadwal_komisi;
DROP POLICY IF EXISTS "admin tulis mezbah"  ON public.mezbah;
DROP POLICY IF EXISTS "admin tulis berita"  ON public.berita;

-- baca publik (jadwal, mezbah, berita) ----------------------------------
CREATE POLICY "publik baca jadwal" ON public.jadwal_komisi
  FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "publik baca mezbah" ON public.mezbah
  FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "publik baca berita" ON public.berita
  FOR SELECT TO anon, authenticated USING (true);

-- tulis admin (hanya user yang sudah login lewat Supabase Auth) ---------
CREATE POLICY "admin tulis jadwal" ON public.jadwal_komisi
  FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "admin tulis mezbah" ON public.mezbah
  FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "admin tulis berita" ON public.berita
  FOR ALL TO authenticated USING (true) WITH CHECK (true);

-- ---------------------------------------------------------------------
-- 2b. HAK AKSES ROLE  (GRANT)
--
--     Policy RLS menentukan "baris mana yang boleh terlihat", tapi GRANT
--     menentukan "boleh menyentuh tabel ini sama sekali atau tidak".
--     Dua hal terpisah: tanpa GRANT, PostgREST menjawab
--     'permission denied for table' dan policy di atas tidak pernah
--     dievaluasi -- gejalanya situs kosong tanpa error yang jelas.
--
--     Supabase umumnya sudah memberi default privilege, tapi kita tidak
--     mau bergantung pada itu. Ditulis eksplisit, dan sengaja tidak
--     memakai GRANT ALL supaya anon tidak dapat menulis.
-- ---------------------------------------------------------------------
GRANT USAGE ON SCHEMA public TO anon, authenticated;

GRANT SELECT                 ON public.jadwal_komisi TO anon, authenticated;
GRANT SELECT                 ON public.mezbah        TO anon, authenticated;
GRANT SELECT                 ON public.berita        TO anon, authenticated;

GRANT INSERT, UPDATE, DELETE ON public.jadwal_komisi TO authenticated;
GRANT INSERT, UPDATE, DELETE ON public.mezbah        TO authenticated;
GRANT INSERT, UPDATE, DELETE ON public.berita        TO authenticated;

-- id memakai GENERATED ... AS IDENTITY, jadi menulis butuh hak atas
-- sequence di belakangnya. Tanpa baris ini, INSERT jadwal/berita gagal
-- dengan 'permission denied for sequence'.
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

