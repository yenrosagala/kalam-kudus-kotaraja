-- ---------------------------------------------------------------------
-- 1. TABEL
--    tanggal  -> DATE  (SQLite pakai TEXT + GLOB; Postgres punya tipe
--                asli jadi validasi & sorting jadi benar)
--    diubah   -> TIMESTAMPTZ (dulu TEXT default datetime('now'))
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.jadwal_komisi (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal         date        NOT NULL,
  tipe            text        NOT NULL DEFAULT 'KOMISI' CHECK (tipe IN ('KU','KOMISI')),
  komisi          text        NOT NULL,
  jenis_ibadah    text        NOT NULL DEFAULT '',
  tuan_rumah      text        NOT NULL DEFAULT '',
  liturgis        text        NOT NULL DEFAULT '',
  pelayan_firman  text        NOT NULL DEFAULT '',
  judul           text        NOT NULL,
  teks            text        NOT NULL DEFAULT '',
  nats_pembimbing text        NOT NULL DEFAULT '',
  tujuan          text        NOT NULL DEFAULT '',
  tempat          text        NOT NULL DEFAULT '',
  waktu           text        NOT NULL DEFAULT '',
  status          text        NOT NULL DEFAULT 'TERJADWAL' CHECK (status IN ('TERJADWAL','SELESAI','BATAL')),
  diubah          timestamptz NOT NULL DEFAULT now(),
  -- Kunci alami. SQLite dulu tidak punya UNIQUE ini, jadi saveKomisi()
  -- mencocokkan (tanggal, komisi) manual sebelum insert/update
  -- (server.js:92-102). Di Postgres kita jadikan constraint supaya
  -- import CSV bisa memakai .upsert() dan tidak pernah dobel.
  CONSTRAINT uq_jk UNIQUE (tanggal, komisi)
);

CREATE TABLE IF NOT EXISTS public.mezbah (
  tanggal      date        PRIMARY KEY,
  judul        text        NOT NULL,
  tema         text        NOT NULL DEFAULT '',
  bacaan       text        NOT NULL DEFAULT '',
  ayat         text        NOT NULL DEFAULT '',
  renungan     text        NOT NULL,
  pesan        text        NOT NULL DEFAULT '',
  refleksi     text        NOT NULL DEFAULT '',
  doa_gkkk     text        NOT NULL DEFAULT '',
  doa_misi     text        NOT NULL DEFAULT '',
  doa_penutup  text        NOT NULL DEFAULT '',
  diubah       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.berita (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal  date        NOT NULL,
  judul    text        NOT NULL,
  ringkasan text       NOT NULL DEFAULT '',
  gambar   text        NOT NULL DEFAULT '',
  isi      text        NOT NULL,
  diubah   timestamptz NOT NULL DEFAULT now()
);

-- idx_jk tidak dibuat lagi: UNIQUE (tanggal, komisi) di atas sudah
-- menghasilkan index dengan kolom & urutan yang sama, sehingga sekaligus
-- melayani query ORDER BY tanggal DESC, komisi.
CREATE INDEX IF NOT EXISTS idx_berita ON public.berita (tanggal DESC, id DESC);

-- ---------------------------------------------------------------------
